function ver_detalhes(botao) {
  document.querySelector(".detalhes_dos_imoveis").classList.add("detalhe");
  document.querySelector("header").classList.add("headerremove");
  document.documentElement.style.overflow = "hidden";

  const detalhes = botao.dataset.unidade;
  sobrados = unidades.find((sobrado) => sobrado.id == detalhes);

  const sobrado1 = document.querySelector(".sobrado");
  const valor = document.querySelector(".valor");
  const sobrado2 = document.querySelector(".sobrado2");
  const informacao = document.querySelector(".informacao");
  const alugar = document.querySelector(".h3");

  const foto_atual = document.querySelector(".foto_atual");
  const total = document.querySelector(".total_fotos");

  conta = 1;

  total.innerHTML = sobrados.quantidade;
  foto_atual.src = sobrados.foto;
  foto_atual.alt = `Foto 1 da ${sobrados.unidade}, imóvel ${sobrados.aluguel.toLowerCase()}`;

  alugar.innerHTML = sobrados.aluguel;
  informacao.innerHTML = sobrados.informacao;
  sobrado1.innerHTML = sobrados.unidade;
  valor.innerHTML = sobrados.preco;
  sobrado2.innerHTML = sobrados.unidade;
}

